"""Freeze local collection IDs and level-11 rarity offsets from the reference catalog."""
import json
from pathlib import Path
import sys

from build_config import load
ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(load()["firstlight_cr"]))
from native_runner.card_specs import build_card_catalog
from native_runner.competitive_data import load_competitive_data

supported = {int(row["card_id"]): int(row["form_availability"])
             for row in load_competitive_data("card_support")["supported_cards"]}
rows = []
for card in build_card_catalog().specs:
    if card.card_id not in supported:
        continue
    minimum = {"Common": 1, "Rare": 3, "Epic": 6, "Legendary": 9, "Champion": 11}[card.categorical_features["rarity"]]
    rows.append((card.card_id, 11-minimum, supported[card.card_id]))
destination = ROOT / "baseline/native_runner/probe/local_card_catalog.inc"
destination.write_text("// Generated by tools/generate_local_cards.py; pinned competitive card support.\n"
    "struct LocalCardLevel { int id; int level; int forms; };\nconstexpr LocalCardLevel kLocalCards[] = {\n" +
    "".join(f"  {{{card}, {level}, {forms}}},\n" for card, level, forms in rows) + "};\n", encoding="utf-8")
print(json.dumps({"cards": len(rows), "file": str(destination)}))
